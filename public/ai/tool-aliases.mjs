export function normalizeEditorTarget(value) {
    const raw = String(value || '').trim().toLowerCase();
    if (!raw) return '';
    if (EDITOR_ALIASES[raw]) return EDITOR_ALIASES[raw];
    if (EDITOR_TARGETS[raw]) return raw;
    const underscored = raw.replace(/[\s-]+/g, '_');
    return EDITOR_ALIASES[underscored] || (EDITOR_TARGETS[underscored] ? underscored : raw);
}

export function studioToolIdForTarget(value) {
    const canonical = normalizeEditorTarget(value);
    if (!canonical) return '';
    return STUDIO_TOOL_IDS[canonical] || canonical;
}

export function editorFileForTarget(value) {
    const target = normalizeEditorTarget(value);
    return EDITOR_TARGETS[target] || null;
}

export function editorTargetIds() {
    return Object.keys(EDITOR_TARGETS);
}
